    history = BASE / '채점 자료/피드백_변경이력' / revision
    drafts = []
    for name, replacements in edits.items():
        path = BASE / '채점 자료' / name / '문항별_채점.json'
        d = json.loads(path.read_text(encoding='utf-8'))
        text = d['feedback']
        for old, new in replacements:
            assert old in text, (name, old)
            text = text.replace(old, new)
        if name == '박주연':
            paragraphs = text.split('\n\n')
            paragraphs[0], paragraphs[1] = paragraphs[1], paragraphs[0]
            text = '\n\n'.join(paragraphs)
        assert len(text) >= len(d['feedback']) * .95
        assert f'최종점수는 {d["registeredTotal"]}점입니다.' in text
        assert not re.search(r'PS-\d|원점수|환산식|순위', text)
        assert '하세요' not in text and '만드세요' not in text
        state = {k: d[k] for k in ('rows', 'rawTotal', 'registeredTotal')}
        drafts.append({'student': name, 'Sid': d['Sid'], 'total': d['registeredTotal'],
                       'scores': [r['registered'] for r in d['rows']], 'oldFeedback': d['feedback'],
                       'feedback': text, 'scoreStateSHA256': hashlib.sha256(json.dumps(state, ensure_ascii=False, sort_keys=True).encode()).hexdigest()})
        print(name, len(d['feedback']), '->', len(text), 'chars')
