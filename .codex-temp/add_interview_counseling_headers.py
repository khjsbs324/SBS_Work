prepared = []
for student, record in RECORDS.items():
    path = SOURCE / student / '면담 일지.md'
    original = path.read_bytes()
    content = original.decode('utf-8')
    if content.startswith('[근태 및 학습상담]'):
        raise RuntimeError(f'상담 양식이 이미 추가되어 있음: {student}')
    if not content.startswith(f'## {student} 학생 심리상태 분석'):
        raise RuntimeError(f'현재 문서 형식 확인 필요: {student}')
    header = (
        '[근태 및 학습상담]\n\n'
        f'* 수강생 수준 : {record["level"]}\n'
        '* 수업 의지 : 상\n'
        '* 수업 태도 : 상\n'
        '* 라포 형성 : 중\n'
        '* 면담 내용\n\n'
        f'  {record["summary"]}\n\n'
        '---\n\n'
    ).encode('utf-8')
    prepared.append((student, path, original, header))

updates = []
for student, path, original, header in prepared:
    path.write_bytes(header + original)
    saved = path.read_bytes()
    assert saved[len(header):] == original, f'기존 본문 보존 오류: {student}'
    updates.append({
        'student': student,
        'path': str(path.relative_to(SOURCE)),
        'prefix_bytes': len(header),
        'original_body_sha256': hashlib.sha256(original).hexdigest(),
        'original_body_preserved': True,
        'level': RECORDS[student]['level'],
        'level_reason': RECORDS[student]['reason'],
    })
    print(f'상단 추가 및 기존 본문 보존 확인: {student}')

result = {
    'instruction': '기존 MD 파일의 본문과 양식을 유지하고 상단에 근태 및 학습상담 양식만 추가함.',
    'fixed_values_source': '사용자 지정: 수업 의지 상, 수업 태도 상, 라포 형성 중. 이 값으로 실제 관찰 근거를 역으로 생성하지 않음.',
    'level_basis': '면담에서 드러난 현재 개념 이해와 수업 수행에 관한 진술에 한정한 잠정 분류. 실기 평가나 제출물 채점 결과가 아님.',
    'files': updates,
}
(ROOT / '.codex-temp/interview-header-update.json').write_text(json.dumps(result, ensure_ascii=False, indent=2) + '\n', encoding='utf-8')
